def generate_sector_map():
    """生成完整的板块映射。"""
    print("=" * 50)
    print("生成板块映射")
    print("=" * 50)

    sector_map = {}

    # 1. 已知映射
    for code, sector in KNOWN_SECTORS.items():
        sector_map[code] = sector

    # 2. 从数据库获取所有股票，对未匹配的分类
    conn = sqlite3.connect(str(DB_PATH))
    cursor = conn.cursor()
    cursor.execute("SELECT code FROM stocks")
    all_codes = [r[0] for r in cursor.fetchall()]
    conn.close()

    print(f"数据库中共 {len(all_codes)} 只股票")

    # 按代码前缀分类
    for code in all_codes:
        if code in sector_map:
            continue

        # 创业板
        if code.startswith(("300", "301")):
            sector_map[code] = "创业板"
        # 科创板
        elif code.startswith(("688", "689")):
            sector_map[code] = "科创板"
        # 深圳主板
        elif code.startswith(("000", "001", "002", "003")):
            sector_map[code] = "深圳主板"
        # 上海主板 - 按细分范围
        elif code.startswith("600"):
            if code in ("600000", "600015", "600016", "600036", "600900",
                        "600908", "600909", "600919", "601009", "601166",
                        "601169", "601229", "601288", "601328", "601398",
                        "601818", "601838", "601860", "601916", "601939",
                        "601988", "601998", "601665", "601825", "601997"):
                sector_map[code] = "银行"
            else:
                sector_map[code] = "沪深主板"
        elif code.startswith("601"):
            sector_map[code] = "沪深主板"
        elif code.startswith("603"):
            sector_map[code] = "中小盘"
        elif code.startswith("605"):
            sector_map[code] = "中小盘"
        else:
            sector_map[code] = "其他"

    print(f"板块映射共 {len(sector_map)} 只股票")

    # 统计分布
    counts = Counter(sector_map.values())
    print("\n板块分布 Top 20:")
    for sector, count in counts.most_common(20):
        print(f"  {sector}: {count}")

    return sector_map


def save_sector_map(sector_map: dict):
    """保存板块映射到 JSON 文件。"""
    output_path = DB_PATH.parent / "sector_map.json"
    output_path.parent.mkdir(parents=True, exist_ok=True)

    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(sector_map, f, ensure_ascii=False, indent=2)

    print(f"\n板块映射已保存到: {output_path}")


if __name__ == "__main__":
    sector_map = generate_sector_map()
    save_sector_map(sector_map)
    print("\n完成!")
